# Recursive path finder to handle nested Kaggle folders
def find_image_root(base_path):
    for root, dirs, files in os.walk(base_path):
        if 'paper' in dirs and 'glass' in dirs:
            return root
    return None

TRAIN_DIR = find_image_root('trashnet_data')
