val_ds.dataset.gray_tx = eval_gray_tx

test_ds = DualStreamDataset(TEST_DIR, eval_rgb_tx, eval_gray_tx, target_classes)

train_loader = DataLoader(train_ds, batch_size=batch_size, shuffle=True)
val_loader = DataLoader(val_ds, batch_size=batch_size, shuffle=False)
test_loader = DataLoader(test_ds, batch_size=batch_size, shuffle=False)

# --- 4. DUAL-STREAM 16-CONV ARCHITECTURE ---
class DualStreamCNN(nn.Module):
    def __init__(self, num_classes):
        super(DualStreamCNN, self).__init__()

        # Streams are 8 Conv layers each (4 blocks of 2)
        self.rgb_branch = self._make_backbone(3)
        self.gray_branch = self._make_backbone(1)

        self.pool = nn.AdaptiveAvgPool2d((4, 4))

        # Fusion Classifier: 256 filters * 4 * 4 * 2 streams = 8192 units
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(256 * 4 * 4 * 2, 512),
            nn.ReLU(),
            nn.BatchNorm1d(512),
            nn.Dropout(0.5),
            nn.Linear(512, num_classes)
        )

    def _make_backbone(self, in_channels):
        return nn.Sequential(
            nn.Conv2d(in_channels, 32, 3, padding=1), nn.BatchNorm2d(32), nn.ReLU(),
            nn.Conv2d(32, 32, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
            nn.Conv2d(32, 64, 3, padding=1), nn.BatchNorm2d(64), nn.ReLU(),
            nn.Conv2d(64, 64, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
            nn.Conv2d(64, 128, 3, padding=1), nn.BatchNorm2d(128), nn.ReLU(),
            nn.Conv2d(128, 128, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
            nn.Conv2d(128, 256, 3, padding=1), nn.BatchNorm2d(256), nn.ReLU(),
            nn.Conv2d(256, 256, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2)
        )

    def forward(self, rgb_x, gray_x):
        rgb_feat = self.pool(self.rgb_branch(rgb_x))
        gray_feat = self.pool(self.gray_branch(gray_x))
        combined = torch.cat((rgb_feat, gray_feat), dim=1)
        return self.classifier(combined)

# --- 5. TRAINING LOOP ---
model = DualStreamCNN(len(target_classes)).to(device)
optimizer = optim.Adam(model.parameters(), lr=0.001, weight_decay=1e-4)
criterion = nn.CrossEntropyLoss()
scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='max', factor=0.5, patience=5)

epochs = 30
best_acc = 0.0

for epoch in range(epochs):
    model.train()
    running_loss, correct, total = 0, 0, 0
    for r_imgs, g_imgs, lbls in train_loader:
        r_imgs, g_imgs, lbls = r_imgs.to(device), g_imgs.to(device), lbls.to(device)
        optimizer.zero_grad()
        out = model(r_imgs, g_imgs)
        loss = criterion(out, lbls)
        loss.backward(); optimizer.step()

        running_loss += loss.item() * r_imgs.size(0)
        _, p = torch.max(out, 1); total += lbls.size(0); correct += (p == lbls).sum().item()

    # Validation
    model.eval()
    v_correct, v_total = 0, 0
    with torch.no_grad():
        for r_imgs, g_imgs, lbls in val_loader:
            r_imgs, g_imgs, lbls = r_imgs.to(device), g_imgs.to(device), lbls.to(device)
            out = model(r_imgs, g_imgs); _, p = torch.max(out, 1)
            v_total += lbls.size(0); v_correct += (p == lbls).sum().item()

    val_acc = 100 * v_correct / v_total
    scheduler.step(val_acc)
    if val_acc > best_acc:
        best_acc = val_acc
        torch.save(model.state_dict(), "dual_stream_best.pth")

    print(f"Epoch {epoch+1:02d} | Loss: {running_loss/total:.4f} | Train: {100*correct/total:.2f}% | Val: {val_acc:.2f}%")

# --- 6. FINAL EVALUATION ---
