# --- 2. CONFIGURATION & DUAL-INPUT DATASET ---
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
target_classes = ['cardboard', 'glass', 'metal', 'paper', 'plastic']
batch_size = 32

class DualStreamDataset(Dataset):
    def __init__(self, root_dir, rgb_tx, gray_tx, classes):
        self.base_ds = datasets.ImageFolder(root_dir)
        self.rgb_tx = rgb_tx
        self.gray_tx = gray_tx
        self.classes = classes
        self.class_to_idx = {cls: i for i, cls in enumerate(classes)}

        # Filter samples to only target classes
        self.samples = []
        for path, label in self.base_ds.samples:
            folder_name = self.base_ds.classes[label]
            if folder_name in self.class_to_idx:
                self.samples.append((path, self.class_to_idx[folder_name]))

    def __len__(self): return len(self.samples)

    def __getitem__(self, idx):
        path, label = self.samples[idx]
        img = datasets.folder.default_loader(path)
        return self.rgb_tx(img), self.gray_tx(img), label

# --- 3. TRANSFORMS (System Robustness) ---
# RGB focuses on color and lighting
rgb_transform = transforms.Compose([
    transforms.RandomResizedCrop(224, scale=(0.7, 1.0)),
    transforms.RandomHorizontalFlip(),
    transforms.RandomApply([transforms.ColorJitter(0.2, 0.2, 0.2)], p=0.5),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
])

# Grayscale focuses purely on edges and textures
gray_transform = transforms.Compose([
    transforms.RandomResizedCrop(224, scale=(0.7, 1.0)),
    transforms.Grayscale(num_output_channels=1),
    transforms.RandomHorizontalFlip(),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.45], std=[0.22])
])

# Evaluation transforms (No augmentation)
eval_rgb_tx = transforms.Compose([
    transforms.Resize((224, 224)), transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
])
eval_gray_tx = transforms.Compose([
    transforms.Resize((224, 224)), transforms.Grayscale(1), transforms.ToTensor(),
    transforms.Normalize(mean=[0.45], std=[0.22])
])

# Load Dataloaders
full_ds = DualStreamDataset(TRAIN_DIR, rgb_transform, gray_transform, target_classes)
train_size = int(0.85 * len(full_ds))
train_ds, val_ds = random_split(full_ds, [train_size, len(full_ds) - train_size])

# Ensure validation doesn't use training augmentations
